-- Kaivor FP125 — shopping watchlist table in KaivorDatabase
-- Run once in Supabase Dashboard > SQL Editor while connected to
-- KaivorDatabase (the same database Reading uses, and the same way
-- the memories/tasks tables in 002 were applied).
-- Additive only: creates one table in public; does not touch
-- existing tables. Safe to rerun.
--
-- NOTE for pasting on the phone: the SQL Editor appends a stray
-- ")" on its own line below a pasted block. Delete any lone ")"
-- after pasting, before tapping Run.

CREATE TABLE IF NOT EXISTS public.shopping_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL CHECK (length(btrim(name)) BETWEEN 1 AND 200),
    store TEXT NOT NULL DEFAULT '' CHECK (length(store) <= 100),
    url TEXT NOT NULL DEFAULT '' CHECK (length(url) <= 2000),
    price NUMERIC(10, 2),
    target_price NUMERIC(10, 2),
    price_note TEXT NOT NULL DEFAULT '' CHECK (length(price_note) <= 200),
    notes TEXT NOT NULL DEFAULT '' CHECK (length(notes) <= 500),
    checkable BOOLEAN NOT NULL DEFAULT TRUE,
    bought BOOLEAN NOT NULL DEFAULT FALSE,
    last_checked TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_shopping_bought_created
    ON public.shopping_items (bought, created_at);
