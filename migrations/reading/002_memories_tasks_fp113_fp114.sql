-- Kaivor FP113/FP114 — memories + tasks tables in KaivorDatabase
-- Run once in Supabase Dashboard > SQL Editor while connected to
-- KaivorDatabase (the same database Reading uses, and the same way
-- the Reading schema in 001_reading_schema.sql was applied).
-- Additive only: creates two tables in public; does not touch
-- existing tables. Safe to rerun.

CREATE TABLE IF NOT EXISTS public.memories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category TEXT NOT NULL DEFAULT 'general',
    title TEXT NOT NULL CHECK (length(btrim(title)) BETWEEN 1 AND 200),
    content TEXT NOT NULL CHECK (length(btrim(content)) BETWEEN 1 AND 4000),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    importance INTEGER NOT NULL DEFAULT 3 CHECK (importance BETWEEN 1 AND 5),
    source TEXT NOT NULL DEFAULT 'manual',
    tags TEXT NOT NULL DEFAULT ''
);
CREATE INDEX IF NOT EXISTS idx_memories_category
    ON public.memories (category);
CREATE INDEX IF NOT EXISTS idx_memories_created
    ON public.memories (created_at DESC);

CREATE TABLE IF NOT EXISTS public.tasks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title TEXT NOT NULL CHECK (length(btrim(title)) BETWEEN 1 AND 200),
    notes TEXT NOT NULL DEFAULT '',
    due_date DATE,
    done BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_tasks_done_due
    ON public.tasks (done, due_date);
CREATE INDEX IF NOT EXISTS idx_tasks_created
    ON public.tasks (created_at DESC);
