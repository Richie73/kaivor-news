-- Kaivor Reading FP043 — Supabase PostgreSQL schema
-- Run once in Supabase Dashboard > SQL Editor while connected to KaivorDatabase.
-- Additive only: creates Reading tables in public; does not alter Supabase auth tables.

CREATE TABLE IF NOT EXISTS public.reading_books (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title TEXT NOT NULL CHECK (length(btrim(title)) BETWEEN 1 AND 240),
    author TEXT,
    book_format TEXT NOT NULL DEFAULT 'other'
        CHECK (book_format IN ('ebook', 'audiobook', 'print', 'magazine', 'newspaper', 'other')),
    status TEXT NOT NULL DEFAULT 'want_to_read'
        CHECK (status IN ('want_to_read', 'reading', 'paused', 'finished', 'abandoned')),
    provider TEXT,
    provider_item_id TEXT,
    description TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT reading_books_provider_identity_unique UNIQUE (provider, provider_item_id)
);

CREATE INDEX IF NOT EXISTS idx_reading_books_status
    ON public.reading_books (status);
CREATE INDEX IF NOT EXISTS idx_reading_books_title
    ON public.reading_books (lower(title));

CREATE TABLE IF NOT EXISTS public.reading_notes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    book_id BIGINT NOT NULL REFERENCES public.reading_books(id) ON DELETE CASCADE,
    note TEXT NOT NULL CHECK (length(btrim(note)) > 0),
    page_reference TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_reading_notes_book
    ON public.reading_notes (book_id, created_at);

CREATE TABLE IF NOT EXISTS public.reading_progress (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    book_id BIGINT NOT NULL REFERENCES public.reading_books(id) ON DELETE CASCADE,
    progress_value DOUBLE PRECISION NOT NULL CHECK (progress_value >= 0 AND progress_value < 'Infinity'::double precision),
    progress_unit TEXT NOT NULL
        CHECK (progress_unit IN ('percent', 'page', 'minute', 'chapter')),
    recorded_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT reading_progress_percent_range
        CHECK (progress_unit <> 'percent' OR progress_value <= 100)
);
CREATE INDEX IF NOT EXISTS idx_reading_progress_book
    ON public.reading_progress (book_id, recorded_at DESC);

CREATE TABLE IF NOT EXISTS public.reading_lists (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL UNIQUE CHECK (length(btrim(name)) BETWEEN 1 AND 120),
    description TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.reading_list_items (
    list_id BIGINT NOT NULL REFERENCES public.reading_lists(id) ON DELETE CASCADE,
    book_id BIGINT NOT NULL REFERENCES public.reading_books(id) ON DELETE CASCADE,
    added_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (list_id, book_id)
);

-- Defence in depth: no anon/authenticated REST access is granted by this migration.
-- The private Render server connects using the database connection string.
ALTER TABLE public.reading_books ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.reading_notes ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.reading_progress ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.reading_lists ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.reading_list_items ENABLE ROW LEVEL SECURITY;

COMMENT ON TABLE public.reading_books IS 'Kaivor Reading library metadata; server-side access only.';
COMMENT ON TABLE public.reading_notes IS 'Private personal reading notes; server-side access only.';
COMMENT ON TABLE public.reading_progress IS 'Reading progress history; server-side access only.';
COMMENT ON TABLE public.reading_lists IS 'User-created reading lists; server-side access only.';
COMMENT ON TABLE public.reading_list_items IS 'Book membership in reading lists; server-side access only.';
